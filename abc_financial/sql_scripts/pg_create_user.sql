-- -- -- START: ONE TIME SET UP
-- CREATE GROUP
CREATE ROLE db_group_admin NOLOGIN;

-- -- -- -- FOR ecom_db
-- BIND DATABASE ON GROUP : ONLY DO THIS FOR NEW DATABASE
GRANT CONNECT, CREATE ON DATABASE ecom_db TO db_group_admin;

-- CREATE SCHEMAS FIRST (So we can alter their privileges)
CREATE SCHEMA IF NOT EXISTS bronze;
CREATE SCHEMA IF NOT EXISTS silver;
CREATE SCHEMA IF NOT EXISTS gold;
-- CREATE SCHEMA IF NOT EXISTS recon;

-- GRANT ALL PRIVILEGES ON ALL SCHEMAS TO GROUP
GRANT ALL PRIVILEGES ON SCHEMA public TO db_group_admin;
GRANT ALL PRIVILEGES ON SCHEMA bronze TO db_group_admin;
GRANT ALL PRIVILEGES ON SCHEMA silver TO db_group_admin;
GRANT ALL PRIVILEGES ON SCHEMA gold TO db_group_admin;
-- GRANT ALL PRIVILEGES ON SCHEMA recon TO db_group_admin;

-- ALTER DEFAULT PRIVILEGES FOR FUTURE TABLES/SEQUENCES IN ALL SCHEMAS
-- For public
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON TABLES TO db_group_admin;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON SEQUENCES TO db_group_admin;

-- For bronze
ALTER DEFAULT PRIVILEGES IN SCHEMA bronze GRANT ALL PRIVILEGES ON TABLES TO db_group_admin;
ALTER DEFAULT PRIVILEGES IN SCHEMA bronze GRANT ALL PRIVILEGES ON SEQUENCES TO db_group_admin;

-- For silver
ALTER DEFAULT PRIVILEGES IN SCHEMA silver GRANT ALL PRIVILEGES ON TABLES TO db_group_admin;
ALTER DEFAULT PRIVILEGES IN SCHEMA silver GRANT ALL PRIVILEGES ON SEQUENCES TO db_group_admin;

-- For gold
ALTER DEFAULT PRIVILEGES IN SCHEMA gold GRANT ALL PRIVILEGES ON TABLES TO db_group_admin;
ALTER DEFAULT PRIVILEGES IN SCHEMA gold GRANT ALL PRIVILEGES ON SEQUENCES TO db_group_admin;


