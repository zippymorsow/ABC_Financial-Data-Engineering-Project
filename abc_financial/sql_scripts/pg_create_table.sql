-- system procedures
CREATE OR REPLACE PROCEDURE create_tbl_sys_migration_dlq()
LANGUAGE PLPGSQL AS $$
BEGIN
    CREATE TABLE IF NOT EXISTS public.sys_migration_dlq (
        dlq_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        failed_at timestamptz DEFAULT CURRENT_TIMESTAMP,
        source_entry_id INT,
        source_pipeline VARCHAR(150),
        raw_payload TEXT,              -- Stores the entire broken row as text/JSON
        error_message TEXT            -- Stores exactly why it failed
    );
END;
$$;

CREATE OR REPLACE PROCEDURE create_tbl_sys_audittrail()
LANGUAGE PLPGSQL AS $$
BEGIN

    CREATE TABLE IF NOT EXISTS public.sys_audittrail(
        sys_audittrail_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
        , sync_batch_id varchar(150) --if of workflow run
        , pipeline_name varchar(150) --name of over all pipeline workflow
        , execution_status varchar(20) --Success,In Progress, Failed, On Hold
        , records_extracted INT DEFAULT 0 -- total number of rows
        , records_loaded INT DEFAULT 0 --total number of successful inserts
        , records_rejected_dlq INT DEFAULT 0 --total number of failed rows sent to DLQ
        , execution_metadata json --this is where currency rate will be logged, or other metadata of other modules as needed; Depends on module; example: {"base":"USD","rate":"53.26","quote":"PHP","date":"2026-09-12"}
        , execution_summary TEXT --"system remarks, or error logged"
        , trigger_started timestamptz DEFAULT CURRENT_TIMESTAMP
        , trigger_ended timestamptz DEFAULT CURRENT_TIMESTAMP
        , execution_duration INTERVAL GENERATED ALWAYS AS (trigger_ended - trigger_started) STORED
        , triggered_by varchar(100) DEFAULT 'sys_audittrail'
        , CONSTRAINT unique_sync_batch UNIQUE (sync_batch_id)
    );

END;
$$;

-- Create the central engine configuration table
CREATE OR REPLACE PROCEDURE create_tbl_sys_pipeline_transform_config()
LANGUAGE PLPGSQL AS $$
BEGIN
    CREATE TABLE IF NOT EXISTS public.sys_pipeline_transform_config (
          sys_pipeline_transform_config_id SERIAL PRIMARY KEY
        , silver_company_id INT NOT NULL -- mappped from silver.company
        , target_table VARCHAR(50) NOT NULL
        , column_name VARCHAR(50) NOT NULL
        , transform_type VARCHAR(20) NOT NULL -- 'upper', 'lower', 'capitalize', 'decimal', 'mask', 'hash', 'none'
        , decimal_scale VARCHAR(10) DEFAULT NULL
        , allow_null BOOLEAN DEFAULT TRUE
        , default_fallback VARCHAR(100) DEFAULT NULL -- E.g., 'unknown@mail.com' or '0' or ''
        , is_pii BOOLEAN DEFAULT FALSE
        , created_at timestamptz
        , created_by varchar(100)
        , modified_at timestamptz
        , deleted_at timestamptz
        , flagdelete boolean
    );
END;
$$;

